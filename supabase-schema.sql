-- 1. Create the orders table
CREATE TABLE IF NOT EXISTS public.orders (
    id TEXT PRIMARY KEY,
    customer_name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    address TEXT,
    city TEXT,
    postal_code TEXT,
    country TEXT DEFAULT 'India',
    payment_method TEXT DEFAULT 'card',
    total NUMERIC(10, 2) NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'confirmed',
    tracking_number TEXT,
    items JSONB DEFAULT '[]'::jsonb,
    estimated_delivery TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Fast search indices
CREATE INDEX IF NOT EXISTS idx_orders_email ON public.orders(email);
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON public.orders(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders(status);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- 4. Public Anonymous Insert Policy (allows checkout customers to submit orders)
DROP POLICY IF EXISTS "Allow public insert for new orders" ON public.orders;
CREATE POLICY "Allow public insert for new orders" 
ON public.orders 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

-- 5. Public Anonymous Read Policy (allows customer order confirmation and order tracking)
DROP POLICY IF EXISTS "Allow public read for order lookups" ON public.orders;
CREATE POLICY "Allow public read for order lookups" 
ON public.orders 
FOR SELECT 
TO anon, authenticated 
USING (true);

-- 6. Authenticated / Admin Update Policy (allows changing status from confirmed -> packing -> shipped)
DROP POLICY IF EXISTS "Allow authenticated updates" ON public.orders;
CREATE POLICY "Allow authenticated updates" 
ON public.orders 
FOR UPDATE 
TO anon, authenticated 
USING (true);

COMMENT ON TABLE public.orders IS 'Storefront orders from Empowix e-commerce application';

-- ====================================================================
-- OPTIONAL: NEWSLETTER SUBSCRIBERS TABLE
-- ====================================================================
CREATE TABLE IF NOT EXISTS public.newsletter_subscribers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.newsletter_subscribers ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public newsletter signup" ON public.newsletter_subscribers;
CREATE POLICY "Allow public newsletter signup" 
ON public.newsletter_subscribers 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

